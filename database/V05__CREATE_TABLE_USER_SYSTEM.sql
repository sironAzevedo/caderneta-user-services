-- Criação da tabela TB_USER_SYSTEM para gerenciar os múltiplos sistemas por usuário
CREATE TABLE IF NOT EXISTS TB_USER_SYSTEM
(
    ID_USER BIGINT NOT NULL,
    SISTEMA VARCHAR(50) NOT NULL,

    PRIMARY KEY (ID_USER, SISTEMA),
    FOREIGN KEY (ID_USER) REFERENCES TB_USER(ID) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS IDX_USER_SYSTEM_SISTEMA ON TB_USER_SYSTEM(SISTEMA);

-- Inserir todos os usuários existentes como CADERNETA (se ainda não existirem)
INSERT INTO TB_USER_SYSTEM (ID_USER, SISTEMA)
SELECT u.ID, 'CADERNETA'
FROM TB_USER u
WHERE NOT EXISTS (
    SELECT 1 FROM TB_USER_SYSTEM s WHERE s.ID_USER = u.ID AND s.SISTEMA = 'CADERNETA'
);

-- Inserir todos os usuários existentes como MARKETPLACE (conforme solicitado para migração manual)
INSERT INTO TB_USER_SYSTEM (ID_USER, SISTEMA)
SELECT u.ID, 'MARKETPLACE'
FROM TB_USER u
WHERE NOT EXISTS (
    SELECT 1 FROM TB_USER_SYSTEM s WHERE s.ID_USER = u.ID AND s.SISTEMA = 'MARKETPLACE'
);
